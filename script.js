// ===========================
// ตัวแปรเกม
// ===========================
let score = 0;
let currentIndex = 0;
let selectedQuestions = [];
let timer;
let timePerQuestion = 20;

// ===========================
// ฟังก์ชันสุ่มคำถาม 10 ข้อ
// ===========================
function shuffleArray(array) {
  for (let i = array.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [array[i], array[j]] = [array[j], array[i]];
  }
}

function startGame() {
  score = 0;
  currentIndex = 0;
  selectedQuestions = [...questions];
  shuffleArray(selectedQuestions);
  selectedQuestions = selectedQuestions.slice(0, 10);
  showQuestion();
}

// ===========================
// แสดงคำถาม
// ===========================
function showQuestion() {
  if(currentIndex >= selectedQuestions.length) {
    showScore();
    return;
  }

  const questionObj = selectedQuestions[currentIndex];
  document.getElementById("question").innerText = `${currentIndex+1}. ${questionObj.question}`;
  
  const optionsDiv = document.getElementById("options");
  optionsDiv.innerHTML = "";
  
  let options = [...questionObj.options];
  shuffleArray(options);

  options.forEach(option => {
    const btn = document.createElement("button");
    btn.innerText = option;
    btn.addEventListener("click", () => selectAnswer(option));
    optionsDiv.appendChild(btn);
  });

  startTimer();
}

// ===========================
// จับคำตอบ
// ===========================
function selectAnswer(option) {
  stopTimer();
  const questionObj = selectedQuestions[currentIndex];
  if(option === questionObj.answer){
    score++;
    document.getElementById("correct-sound").play();
  } else {
    document.getElementById("wrong-sound").play();
  }
  currentIndex++;
  setTimeout(showQuestion, 500);
}

// ===========================
// แสดงคะแนน
// ===========================
function showScore() {
  document.getElementById("quiz-container").innerHTML = `<h2>คุณทำคะแนนได้ ${score} / ${selectedQuestions.length}</h2>
  <button onclick="startGame()">เล่นใหม่</button>`;
}

// ===========================
// ระบบจับเวลา
// ===========================
function startTimer() {
  let timeLeft = timePerQuestion;
  document.getElementById("timer").innerText = `เวลา: ${timeLeft} วินาที`;
  timer = setInterval(() => {
    timeLeft--;
    document.getElementById("timer").innerText = `เวลา: ${timeLeft} วินาที`;
    if(timeLeft <= 0){
      stopTimer();
      currentIndex++;
      showQuestion();
    }
  },1000);
}

function stopTimer() {
  clearInterval(timer);
}

// ===========================
// เริ่มเกม
// ===========================
startGame();
